# -*- coding: utf-8 -*-
"""第五章 国内外对比总览"""
from sapc_common import (COUNT, add_heading_cn, add_body, add_quote, add_table,
                         add_figure, add_page_break)


def build_chapter5(doc, F):
    COUNT.set_chapter(5)
    add_heading_cn(doc, "第五章 国内外研究现状对比总览", level=1)

    add_body(doc, """
前三章已沿"器件—失效模式—失效机理"三模块主线，分别在各模块末尾对国内外进展作了对照与评述。本章在此基础上作横向汇总，从三模块综合水平（5.1）、多维度量化对比（5.2）与研究演进脉络（5.3）三个视角，给出 SAPC 失效模式与失效机理研究国内外格局的总体判断，为第六章凝练研究空白作铺垫。需重申本综述对"国内/国外文献"的界定：以撰写语言为准，中文为国内、外文为国外。
""")

    # ---------------------------------------------------------------- 5.1
    add_heading_cn(doc, "5.1 三模块研究水平的综合对照", level=2)
    add_body(doc, """
图5-1以雷达图综合对照国内外（外文/中文文献）在器件理解、失效模式表征、失效机理理论、原位表征、工程转化与原创模型六个维度上的研究水平。总体格局可概括为"国外引领范式、国内深化工程"：国外在失效机理理论、原位表征与原创模型上长期领先，得益于 NASA NEPP、CALCE、KEMET 等机构与日系厂商的长期积累；国内在工程转化（材料量产、车规落地、可靠性数据）上快速逼近甚至在某些工程指标上不落下风，但在机理理论的原创性与原位多物理场表征的系统性上仍存明显差距。值得注意的是，"工程转化"维度国内外接近，反映出国产 SAPC 产业链的成熟，但这并不等同于对失效物理"定义权"的掌握。
""")
    add_figure(doc, F["radar_3module"],
               "国内外 SAPC 研究水平六维雷达对照（0—10，定性）",
               width_cm=12.5,
               note="图片解读：国外（蓝）在机理理论、原位表征、原创模型上领先，国内（红）在工程转化上接近；"
                    "评分为基于文献计量与内容分析的定性归纳。作者自绘。")
    add_body(doc, """
对这一格局的成因，可从研究生态的差异加以理解。国外（尤以美、日、欧）拥有 NASA NEPP、CALCE 等长期专注电子元器件可靠性的机构，以及 KEMET、Panasonic、Nichicon、Nippon Chemi-Con 等深耕数十年的厂商，形成了"机理研究—判据制定—产品迭代"的闭环，且其成果以英文发表、被国际标准与手册广泛采纳，掌握了失效物理的"定义权"。国内的研究生态则呈"高校/院所偏机理验证、企业偏工艺产品"的分工，二者之间的贯通与积累尚不及国外深厚，且高水平成果有相当部分以英文发表（按本综述界定应归入外文组），客观上削弱了中文文献在原创机理上的显示度。理解这一成因，有助于客观看待"国外引领、国内跟进"的现状：差距既有研究历史与积累的客观原因，也有成果发表语言与评价导向的结构性因素，而非简单的能力高下之分。
""")

    # ---------------------------------------------------------------- 5.2
    add_heading_cn(doc, "5.2 多维度量化对比", level=2)
    add_body(doc, """
图5-2从起步时间、研究深度、原创性、工程落地、标准/判据话语权五个维度作柱状对比。可见：在起步时间与原创性上，国外（外文文献）显著领先——PEDOT 机理、聚合物电容失效判据、关键加速试验方法多由国外首创；在工程落地上国内（中文文献/企业）已与国外比肩；而在"标准/判据话语权"上，国内仍以引用国外判据为主，缺乏面向 SAPC 的自主失效率基准与统一失效阈值标准。这一对比清晰地指向：国内 SAPC 研究的短板不在"做不出来"，而在"定义不了标准"——即缺乏原创机理理论与权威判据体系。
""")
    add_figure(doc, F["progress_bars"],
               "国内外多维度对比（起步时间/深度/原创/工程落地/标准话语权）",
               width_cm=14.0,
               note="图片解读：国外在起步、原创、标准话语权上领先，国内在工程落地上接近。评分为定性归纳。作者自绘。")
    add_body(doc, """
从文献计量的角度可进一步印证这一格局。在原创性指标（如奠基性/高被引论文、首次提出机理或判据者）上，国外占据绝对优势：PEDOT 的颗粒金属/导电畴热降解图景、聚合物电容湿热失效与分层机理、聚合物钽 ESR 热氧化退化等关键认识，均首发于外文文献与机构报告；而中文文献中，原创性机理理论相对较少，更多是对国外机理框架的验证、细化与本土化应用，或集中于材料工艺改进与对照器件（如 BME MLCC、薄膜自愈）。在产出数量上，近年中文文献增长迅速，在固态/聚合物铝电容的工艺、车规可靠性评估与相邻领域（薄膜、超级电容）的退化研究上产出可观，反映出国内研究力量的快速壮大；但"数量接近"不等于"影响力对等"——衡量影响力的高被引、被国际标准/手册采纳、被同行机理命名引用等指标，国外仍明显领先。这一"量近质差"的现象，正是国内 SAPC 研究当前阶段的真实写照。
""")
    add_body(doc, """
需要客观指出的是，上述对比中的评分与判断属定性归纳，旨在刻画总体格局而非精确计量；其依据是本综述对纳入文献的内容分析与来源结构（参见第一章图1-4），而非严格的文献计量统计。即便如此，"国外引领范式、国内深化工程"这一总体判断，在器件、失效模式、失效机理三模块的逐节评述中反复得到印证，具有较强的稳健性。对国内研究而言，其真正的提升空间不在于"多发文章"，而在于"提出原创机理理论、建立自主判据标准、掌握失效物理的定义权"——这恰是本学位论文努力的方向。
""")
    add_body(doc, """
表5-1将三模块的国内外对比汇总为一表，作为本综述对照分析的总索引。综合三模块可见，国内外差距并非均匀分布：在"器件"模块差距最小（产业链成熟），在"失效模式"模块差距居中（判据待统一），在"失效机理"模块差距最大（原创理论与多应力耦合定量化薄弱）。这一"差距梯度"恰好提示了本学位论文最有价值的着力点应落在失效机理模块，尤其是多应力耦合与 PEDOT 退化动力学的定量化。
""")
    add_table(
        doc,
        ["模块", "国外突出之处", "国内突出之处", "主要差距", "差距程度"],
        [
            ["器件结构与材料", "PEDOT 材料/工艺与产品标准首创", "材料量产、低ESR长寿命产品", "最高可靠等级一致性、基础工艺数据库", "较小"],
            ["失效模式", "ESR/DCL 主导认识、EoL 判据提出", "良性失效工程把握、车规数据", "统一失效阈值/判据缺位", "居中"],
            ["失效机理", "PEDOT 机理理论、原位表征、原创模型", "材料机理细化、对照器件机理、工程验证", "原创理论弱、多应力耦合未定量", "较大"],
        ],
        caption="三模块国内外研究现状对比总览",
        col_widths=[2.6, 4.2, 4.0, 3.8, 1.6],
    )

    # ---------------------------------------------------------------- 5.3
    add_heading_cn(doc, "5.3 研究演进脉络与态势", level=2)
    add_body(doc, """
图5-3以时间轴呈现 SAPC 相关失效机理研究的演进：自1969年 Prokopowicz-Vaskas 陶瓷电容寿命经验式、1990年 Waser 氧空位迁移模型等对照器件机理奠基，至2000年 PEDOT 固态电容商业化、2008年 PEDOT:PSS 热降解机理研究、2016年前后 CALCE 聚合物铝湿热失效研究、2019年 NASA 聚合物钽 ESR 热氧化研究、2020年 KEMET 分层机理，再到2025年前后的去掺杂调控与原位分析。这一脉络显示：SAPC 机理研究正从"借用对照器件经典机理"走向"针对 PEDOT 阴极的专门机理"，从"单应力唯象"走向"多应力与原位多物理场"，从"机理定性指认"走向"退化动力学定量化"。本学位论文正处于这一演进的前沿节点上。
""")
    add_figure(doc, F["timeline_mech"],
               "SAPC 相关失效机理研究的演进时间轴",
               width_cm=15.5,
               note="图片解读：蓝点为对照器件经典机理奠基，红点为 SAPC/聚合物阴极专门机理进展；"
                    "趋势为从借用经典、单应力唯象走向专门机理、多应力与定量化。年份为代表性节点。作者自绘。")
    add_quote(doc, """
总览判断：国内外 SAPC 失效研究呈"国外引领范式、国内深化工程"的互补格局，差距集中在原创机理理论、强物理嵌入与跨工况泛化三方面，且差距在三模块上呈"器件小、模式中、机理大"的梯度。这一判断为第六章逐条凝练研究空白、并对接学位论文研究内容提供了直接依据。
""")
    add_page_break(doc)
