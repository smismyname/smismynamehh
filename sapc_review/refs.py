def format_ieee(ref):
    """IEEE-style string with DOI / [DOI待核验] flag."""
    parts = []
    parts.append(f"[{ref['n']}] {ref['authors']},")
    title = f"\u201c{ref['title']},\u201d"
    parts.append(title)
    venue = ref["venue"]
    if ref.get("year"):
        venue = f"{venue}, {ref['year']}"
    parts.append(venue + ".")
    if ref.get("doi"):
        tail = f"DOI: {ref['doi']}."
        if "核验" in (ref.get("note") or "") and "DOI建议核验" in ref["note"]:
            tail += " [DOI待核验]"
    else:
        tail = "[DOI待核验]"
    parts.append(tail)
    line = " ".join(parts)
    if ref.get("url"):
        line += f" 链接: {ref['url']}"
    return line


