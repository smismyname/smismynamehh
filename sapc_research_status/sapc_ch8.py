def build_chapter8(doc, F):
    add_heading_cn(doc, "第八章 状态监测与PHM研究现状", level=1)
    add_body(doc, """
本章对应主线的"状态监测与PHM"环节。如果说寿命建模（第七章）回答"能用多久"，那么状态监测与故障预测健康管理（Prognostics and Health Management, PHM）回答"现在状态如何、还能用多久、何时维护"。对SAPC而言，由于其退化以ESR上升为主、物理清晰、可在线获取，监测具有良好的物理基础。本章先建立PHM框架与健康指标选择（8.1），继而评述ESR/容值在线辨识（8.2）、阻抗谱与特征频率法（8.3）、数据驱动在线RUL（8.4），再梳理国内进展（8.5）并评述（8.6）。
""")

    # ---------------------------------------------------------------- 8.1
    add_heading_cn(doc, "8.1 PHM框架与健康指标选择", level=2)
    add_body(doc, """
PHM的一般框架包括：数据采集→特征提取→健康指标（HI）构建→状态评估/故障诊断→剩余寿命预测→维护决策。其核心前提是选择对退化敏感、可在线获取、物理意义明确的健康指标。对SAPC，ESR是首选健康指标：它对主导退化（PEDOT去掺杂）高度敏感、随退化单调上升、物理意义清晰，且可通过电压/电流测量在线估计；容值作为辅助指标，在后期下降时用于确认；漏电流则在漏电主导失效中作为补充。图33示意了ESR作为主导健康指标、容值后期下降的退化轨迹。
""")
    add_figure(doc, F["fig_health_indicator"], "ESR作为SAPC的主导健康指标（容值后期下降）")
    add_body(doc, """
寿命终点（EoL）判据通常以ESR升至初值某倍数（常用2倍）为准，辅以容值下降阈值。值得强调的是，SAPC以ESR为主导健康指标，这与液态铝电解（ESR与容值并重）和MLCC（绝缘电阻/漏电为主）不同，体现了"健康指标随器件机理而异"的原则。一个良好的SAPC监测方案，应当紧扣其"ESR主导"的退化本质，而非照搬其他器件的指标体系。
""")

    # ---------------------------------------------------------------- 8.2
    add_heading_cn(doc, "8.2 ESR与容值的在线辨识方法", level=2)
    add_body(doc, """
在线辨识旨在不停机、不额外接入仪器的条件下，从变换器正常运行的电压/电流信号中估计电容的ESR与容值。其基本原理是：电容端电压纹波与流过电流之间的关系蕴含了C与ESR的信息。常见方法可归纳为：
""")
    add_list_item(doc, "（1）纹波分量法：提取电容电流与电压纹波，在特定频率下由纹波电压/电流之比估计阻抗，进而分离ESR与C。实现简单，但易受噪声与频率选择影响。")
    add_list_item(doc, "（2）开关同步/最小二乘法：利用开关周期内的电流—电压片段，以最小二乘拟合等效电路参数，精度较高，但需较准确的电流采样与同步。")
    add_list_item(doc, "（3）小信号注入法：主动注入特定频率扰动并测量响应，提高信噪比与可控性，但需附加注入电路。")
    add_list_item(doc, "（4）观测器/模型法：以等效电路为模型，用卡尔曼滤波或参数自适应观测器在线递推估计参数。")
    add_list_item(doc, "（5）机器学习辅助估计：以神经网络从电气波形直接映射到C/ESR，提升复杂工况下的鲁棒性。")
    add_body(doc, """
图34对比了各类方法的C/ESR估计精度的代表性水平：随着方法从被动纹波法向主动注入、观测器与机器学习辅助演进，ESR估计误差从十余个百分点降至个位数百分点。对SAPC而言，由于ESR本身很小（毫欧级），其相对测量更具挑战——小的绝对误差即对应较大的相对误差，对采样精度与算法鲁棒性要求更高。这是SAPC监测区别于液态铝电解（ESR较大、相对易测）的一个技术难点。
""")
    add_body(doc, """
进一步看，毫欧级ESR在线辨识面临三重工程约束。其一是信噪比：在低ESR下，纹波电压中由ESR贡献的分量很小，易被开关噪声、采样量化误差与寄生参数淹没，需要高分辨率采样与精细的同步/滤波；其二是寄生解耦：印制板走线、端子与测量回路的寄生电阻/电感与器件ESR同量级甚至更大，必须在模型与标定中予以扣除，否则将系统性高估ESR；其三是工况依赖：ESR随频率与温度变化，在线辨识须在已知或同步测量的频率与温度下进行，并据此归一化。正因这些约束，单纯沿用为液态铝电解开发的辨识算法往往不能直接满足SAPC的精度要求，发展面向毫欧级、强寄生背景下的高精度辨识方法，是SAPC状态监测的关键技术增量。
""")
    add_figure(doc, F["fig_monitoring_accuracy"], "在线C/ESR辨识方法的估计精度对比")

    # ---------------------------------------------------------------- 8.3
    add_heading_cn(doc, "8.3 阻抗谱与特征频率监测", level=2)
    add_body(doc, """
阻抗谱（EIS）通过宽频带阻抗测量，可比单频法更全面地刻画退化（第四章）。但完整EIS在线实施成本高，工程上常退化为"特征频率法"：在对ESR最敏感的频段（通常接近自谐振频率，此处阻抗≈ESR）选取一个或几个特征频率进行监测，以平衡信息量与实现复杂度。这一思路在国内外的在线监测研究中均有体现。对SAPC，由于其自谐振频率较高（低ESL），特征频率的选择需考虑测量带宽与噪声，监测电路设计与算法需协同优化。
""")
    add_body(doc, """
此外，温度是ESR监测必须解耦的干扰量：ESR本身随温度变化（第四章），若不校正温度影响，会把"温度引起的ESR变化"误判为"退化引起的ESR变化"。因此，先进的SAPC监测方案需引入温度测量与ESR(T)校正，把"老化引起的ESR上升"从"温度引起的ESR波动"中分离出来。这一温度解耦问题，在以ESR为核心指标的SAPC监测中尤为关键。
""")

    # ---------------------------------------------------------------- 8.4
    add_heading_cn(doc, "8.4 数据驱动的在线RUL预测", level=2)
    add_body(doc, """
在获取ESR/容值退化序列后，可用第七章所述的数据驱动或物理信息混合方法进行在线RUL预测。与离线建模不同，在线RUL强调实时性、对新数据的自适应更新以及对不确定性的量化（给出预测区间而非单点）。国内外在LSTM、CNN-LSTM、以及物理信息神经网络用于电容/超级电容RUL在线预测方面已有较多成果，并逐步引入不确定性量化（如贝叶斯方法、分位数回归）。
""")
    add_body(doc, """
将监测与预测闭环，即构成完整的SAPC-PHM：在线辨识ESR→温度解耦→退化趋势提取→（物理信息约束的）RUL预测→维护/降额决策。然而，这一闭环在SAPC上的端到端验证仍不充分：一方面，缺乏公开的SAPC全寿命退化数据集；另一方面，监测精度（毫欧级ESR）、温度解耦与跨工况泛化三重挑战叠加，使高可信的SAPC-PHM尚未成熟。这与第七章的建模空白（G4）相互印证。
""")
    add_quote(doc, """
监测评述：SAPC的"ESR主导"为监测提供了清晰靶标，但"毫欧级ESR的高精度在线辨识＋温度解耦＋跨工况泛化"三重难点叠加，使其监测难度并不低于液态铝电解。监测精度直接决定RUL预测精度，因此提升ESR在线辨识与温度解耦能力，是SAPC-PHM落地的关键瓶颈。
""")

    # ---------------------------------------------------------------- 8.5
    add_heading_cn(doc, "8.5 国内研究进展：在线监测与智能预测", level=2)
    add_body(doc, """
国内在状态监测与PHM上具有较强实力，尤其在电力电子背景的在线监测算法方面。代表性工作包括：重庆大学等团队提出的直流母线电容灰箱（grey-box）在线监测方法，将物理等效电路与数据辨识相结合，在线估计ESR/容值，体现了"物理＋数据"的混合监测思路；多所高校在基于运行数据的电容参数辨识、健康评估方面有积累。在智能预测方面，国内的CNN-LSTM电容老化评估与RUL预测（考虑参数离散）、超级电容的物理信息神经网络RUL预测等工作，显示出方法学上的活力与一定的国际显示度。
""")
    add_body(doc, """
不过，国内监测/预测研究的对象多为液态铝电解（母线电容）、钽与超级电容，专门针对叠层铝—聚合物SAPC、解决其"毫欧级ESR辨识＋温度解耦"特有难点的工作仍偏少。这再次呈现"方法学能力强、SAPC专用研究弱"的格局。把国内成熟的在线辨识与智能预测能力迁移并专门化到SAPC，是一个现实且高价值的方向。
""")

    # ---------------------------------------------------------------- 8.6
    add_heading_cn(doc, "8.6 本章评述与小结", level=2)
    add_body(doc, """
本章表明，SAPC监测应以ESR为主导健康指标，在线辨识方法已从被动纹波法发展到主动注入、观测器与机器学习辅助，精度持续提升；阻抗谱/特征频率法与温度解耦是关键技术；数据驱动与物理信息混合支撑在线RUL。监测—预测—决策的闭环是SAPC-PHM的目标形态。
""")
    add_quote(doc, """
本章评述（共性不足）：其一，SAPC毫欧级ESR的高精度在线辨识与温度解耦尚未很好解决，监测误差制约RUL精度；其二，缺乏公开的SAPC全寿命退化数据集，端到端PHM验证不足；其三，国内"通用监测能力强、SAPC专用化弱"。这些与第七章建模空白共同指向研究空白G4。
""")
    add_body(doc, """
承上启下，性能、失效、机理、建模与监测共同构成了SAPC可靠性的"技术内核"，但其研究的价值最终要在具体应用场景中被检验与定义。不同应用对SAPC提出的可靠性要求差异巨大，并反过来塑造了研究的重点。因此，下一章从横向应用视角，评述数据中心/服务器、消费电子、汽车电子、5G通信等领域对SAPC的可靠性需求与相应研究现状。
""")
